// Types of Binary Tree

/*
1. Full Binary Tree
2. Complete Binary Tree
3. Perfect Binary Tree
4. Balanced Binary Tree
5. Degenerate Tree
*/

/*
Full Binary Tree: A binary tree where every node has either 0 or 2 children.

Complete Binary Tree: A binary tree where all levels are fully filled except possibly the last, which is filled from left to right.

Perfect Binary Tree: A binary tree where all internal nodes have two children, and all leaves are at the same level.

Balanced Binary Tree: A binary tree where the height difference between the left and right subtrees of every node is at most 1.

Degenerate Tree: A tree where each parent node has only one child, making it essentially a linked list.
*/